<?php

declare(strict_types=1);

namespace App\Models;

use App\Enums\Inventory\StockMovementType;
use App\Enums\ShopInvoice\ShopCreditNoteDirection;
use App\Enums\ShopInvoice\ShopCreditNoteInventoryAction;
use Database\Factories\ShopCreditNoteItemFactory;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;

class ShopCreditNoteItem extends Model
{
    /** @use HasFactory<ShopCreditNoteItemFactory> */
    use HasFactory;

    protected $fillable = [
        'shop_credit_note_id',
        'shop_invoice_item_id',
        'product_id',
        'product_grade',
        'product_name',
        'unit',
        'price_unit',
        'original_quantity',
        'original_unit_price',
        'original_line_total',
        'adjusted_quantity',
        'adjusted_unit_price',
        'line_credit_amount',
        'direction',
        'inventory_action',
        'notes',
    ];

    protected function casts(): array
    {
        return [
            'original_quantity' => 'decimal:4',
            'original_unit_price' => 'decimal:2',
            'original_line_total' => 'decimal:2',
            'adjusted_quantity' => 'decimal:4',
            'adjusted_unit_price' => 'decimal:2',
            'line_credit_amount' => 'decimal:2',
            'direction' => ShopCreditNoteDirection::class,
            'inventory_action' => ShopCreditNoteInventoryAction::class,
        ];
    }

    protected static function booted(): void
    {
        static::deleting(function (ShopCreditNoteItem $item): void {
            if ($item->creditNote?->isApproved()) {
                throw new \RuntimeException(
                    "Cannot delete items from approved credit note {$item->creditNote->credit_note_number}."
                );
            }
        });
    }

    public function creditNote(): BelongsTo
    {
        return $this->belongsTo(ShopCreditNote::class, 'shop_credit_note_id');
    }

    public function invoiceItem(): BelongsTo
    {
        return $this->belongsTo(ShopInvoiceItem::class, 'shop_invoice_item_id');
    }

    public function product(): BelongsTo
    {
        return $this->belongsTo(Product::class);
    }

    /**
     * Stock movements generated by this credit note item.
     *
     * @return Builder<StockMovement>
     */
    public function stockMovements(): Builder
    {
        return StockMovement::query()
            ->where('type', StockMovementType::SaleReversal->value)
            ->where('notes', 'like', "%NoteItem: {$this->id};%");
    }

    public function totalRestoredStockQuantity(): float
    {
        return round((float) $this->stockMovements()->sum('quantity'), 3);
    }
}
